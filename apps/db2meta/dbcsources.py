"""Generates where every DBC store member is loaded from in the 3.4.3.54261 tables.

Reads dbcmatch.py's results (--json) and apps/db2meta/dbcsources.json, the decisions for the
members the data cannot place by itself, and writes src/server/shared/DataStores/DBCSources.h:
one source per loaded format column of each store.

A member is placed without a decision when
  - it is the store's index: the record id;
  - one 54261 column agrees with it on >= 90% of the shared ids and no other column agrees as
    well, and its 3.3.5 values are not all alike;
  - its best columns are the record id and the file's index column, or the parent id and the
    file's parent column (the same values either way).
Everything else needs an entry in dbcsources.json, and the run fails listing what is missing:
no member is ever loaded from a guess the file does not record.

    python apps/db2meta/dbcsources.py --map .agents/plans/frostforge-server/data-map.json
"""

