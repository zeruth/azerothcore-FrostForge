def column_label(meta, label: str):
    """'12[3]' -> (12, 3); '7' -> (7, 0)."""
    m = re.fullmatch(r"(\d+)(?:\[(\d+)\])?", label)
    return int(m.group(1)), int(m.group(2) or 0)


def resolve(r: dict, x: dict, decided: dict) -> tuple[str, str] | None:
    """(C++ initializer, comment) for one member, or None when it needs a decision."""
    joined = "keys" in r
    meta = r if joined else db2read.metas()[r["table"]]
    member = x["member"]
    if member in decided and not member.startswith("_"):
        d = decided[member]
        why = d["why"] + (f" [fixup: {d['fixup']}]" if "fixup" in d else "")
        return source(meta, d["source"], d.get("default", 0)), why
    # "_arrays": {"multiplier": [[field, first element, count, why], ...]}: an AC array split
    # over several 54261 arrays, element by element in order
    m = re.fullmatch(r"(\w+)\[(\d+)\]", member)
    if m and m.group(1) in decided.get("_arrays", {}):
        i = int(m.group(2))
        for field, first, count, why in decided["_arrays"][m.group(1)]:
            if first <= i < first + count:
                if field == "zero":
                    return source(meta, "zero"), why
                return source(meta, f"{field}[{i - first}]"), why
    if x["kind"] in "nd":
        return "{ DBCSourceKind::Id }", "the record id"
    if x.get("locale"):
        return "{ DBCSourceKind::Zero }", "another locale: a 54261 table file holds one"
    hits = x["hits"]
    if x["distinct"] <= 1 or not hits or hits[0][0] < 0.9:
        return None
    best = [h for h in hits if h[0] == hits[0][0]]
    labels = {h[1] for h in best}
    pct = f"{hits[0][0]:.0%}"
    if len(best) == 1:
        return source(meta, best[0][1]), f"agrees on {pct}"
    if joined:
        return None
    if meta.index_field != -1 and labels == {"id", str(meta.index_field)}:
        return "{ DBCSourceKind::Id }", f"the record id (agrees on {pct})"
    if meta.parent_index_field != -1 and labels == {"parent", str(meta.parent_index_field)}:
        return "{ DBCSourceKind::ParentId }", f"the parent id (agrees on {pct})"
    return None


def positional(r: dict, resolved: list) -> None:
    """Elements of a member array the data cannot place alone (all alike, or tied with other
    columns) take the element of the 54261 array their placed siblings land in, at the same
    offset, when that element agrees on >= 90% of the shared ids."""
    if "keys" in r:
        effect_positional(r, resolved)
        return
    meta = db2read.metas()[r["table"]]
    arrays: dict[str, dict[int, int]] = {}
    for k, x in enumerate(r["rows"]):
        m = re.fullmatch(r"(\w+)\[(\d+)\]", x["member"])
        if m:
            arrays.setdefault(m.group(1), {})[int(m.group(2))] = k
    for base, elements in arrays.items():
        offsets = set()
        for i, k in elements.items():
            res = resolved[k]
            m = res and re.fullmatch(r"\{ DBCSourceKind::Column, (\d+), (\d+) \}", res[0])
            if m and "agrees" in res[1]:
                offsets.add((int(m.group(1)), int(m.group(2)) - i))
        how = "placed elements"
        if not offsets:
            # no element placed alone (the values changed between builds, e.g. holiday dates):
            # the alignment most elements' best column agrees on, when it is a clear majority
            votes: dict[tuple[int, int], int] = {}
            voters = 0
            for i, k in elements.items():
                x = r["rows"][k]
                if x["distinct"] <= 1 or not x["hits"]:
                    continue
                voters += 1
                m = re.fullmatch(r"(\d+)\[(\d+)\]", x["hits"][0][1])
                if m:
                    key = (int(m.group(1)), int(m.group(2)) - i)
                    votes[key] = votes.get(key, 0) + 1
            if votes:
                key, n = max(votes.items(), key=lambda v: v[1])
                if n >= 3 and n * 5 >= voters * 3:
                    offsets, how = {key}, f"the best column of {n} of {voters} elements"
        if len(offsets) != 1:
            continue
        ((field, off),) = offsets
        for i, k in elements.items():
            if resolved[k] is not None or not 0 <= i + off < meta.fields[field].array:
                continue
            label = f"{field}[{i + off}]" if meta.fields[field].array > 1 else f"{field}"
            agree = dict((h[1], h[0]) for h in r["rows"][k]["hits"]).get(label, 0)
            resolved[k] = (source(meta, label), f"{base}[] lies in column {field} at offset {off}, "
                                                f"by {how} (this element agrees on {agree:.0%})")


def effect_positional(r: dict, resolved: list) -> None:
    """A joined store's member arrays: an element the data cannot place alone takes the column
    its placed siblings share, at its own effect (X[2] -> SpellEffect.c@2 when X[0] is
    SpellEffect.c@0) or its own array element (X[2] -> T.c[2] when X[0] is T.c[0])."""
    elements: dict[str, dict[int, int]] = {}
    for k, x in enumerate(r["rows"]):
        m = re.fullmatch(r"(\w+)\[(\d+)\]", x["member"])
        if m:
            elements.setdefault(m.group(1), {})[int(m.group(2))] = k
    for base, members in elements.items():
        patterns = set()
        for i, k in members.items():
            res = resolved[k]
            if res is None or "agrees" not in res[1]:
                continue
            label = r["rows"][k]["hits"][0][1]
            m = re.fullmatch(r"(\w+\.\d+)(\[\d+\])?@(\d+)", label)
            if m and int(m.group(3)) == i:
                patterns.add(f"{m.group(1)}{m.group(2) or ''}@{{i}}")
                continue
            m = re.fullmatch(r"(\w+\.\d+)\[(\d+)\]", label)
            if m and int(m.group(2)) == i:
                patterns.add(f"{m.group(1)}[{{i}}]")
        if len(patterns) != 1:
            continue
        (pattern,) = patterns
        for i, k in members.items():
            if resolved[k] is not None:
                continue
            label = pattern.format(i=i)
            agree = dict((h[1], h[0]) for h in r["rows"][k]["hits"]).get(label, 0)
            resolved[k] = (source(r, label), f"{base}[] is {pattern.format(i='i')} by its placed elements "
                                             f"(this one agrees on {agree:.0%})")


def joined_tables(r: dict) -> list[str]:
    """A joined store's tables in Joins order (spellmatch.py's keys)."""
    return list(r["keys"])


def source(meta, label: str, default: int = 0) -> str:
    if label == "id":
        return "{ DBCSourceKind::Id }"
    if label == "parent":
        return "{ DBCSourceKind::ParentId }"
    if label == "zero":
        return "{ DBCSourceKind::Zero }"
    if isinstance(meta, dict):
        # a joined store (meta is its result): Table.column[element]@effect
        m = re.fullmatch(r"(\w+)\.(\d+)(?:\[(\d+)\])?(?:@(\d+))?", label)
        if not m:
            raise SystemExit(f"{meta['struct']}: cannot read the source {label}")
        tables = joined_tables(meta)
        t, field, index = m.group(1), int(m.group(2)), int(m.group(3) or 0)
        tmeta = db2read.metas()[t]
        if field >= tmeta.file_field_count or index >= tmeta.fields[field].array:
            raise SystemExit(f"{t}: no column {label}")
        effect = f", {m.group(4)}" if m.group(4) is not None else ""
        if default:
            effect = (effect or ", DBC_SOURCE_NO_EFFECT") + f", uint32({default})"
        return f"{{ DBCSourceKind::Column, {field}, {index}, {tables.index(t)}{effect} }}"
    field, index = column_label(meta, label)
    if field >= meta.file_field_count or index >= meta.fields[field].array:
        raise SystemExit(f"{meta.name}: no column {label}")
    return f"{{ DBCSourceKind::Column, {field}, {index} }}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--map", type=Path, required=True)
    ap.add_argument("--spell-map", type=Path, help="spellmatch.py's --json: SpellEntry over the spell tables")
    ap.add_argument("--pending", action="store_true", help="list undecided members and exit")
    args = ap.parse_args()
    data = json.loads(args.map.read_text(encoding="utf-8"))
    if args.spell_map:
        # SpellEntry comes from the joined spell tables, not from 54261's Spell (three strings)
        data["results"] = [r for r in data["results"] if r["store"] != "sSpellStore"]
        data["results"].append(json.loads(args.spell_map.read_text(encoding="utf-8")))
    decisions = json.loads(DECISIONS.read_text(encoding="utf-8")) if DECISIONS.exists() else {}
    out, pending, complete = [HEADER], [], []
    for r in data["results"]:
        decided = decisions.get(r["table"], {})
        resolved = [resolve(r, x, decided) for x in r["rows"]]
        positional(r, resolved)
        lines = []
        for x, res in zip(r["rows"], resolved):
            if res is None:
                pending.append((r, x))
                continue
            lines.append(f"        {res[0]},  // {x['member']}: {res[1]}")
        if any(res is None for res in resolved):
            continue    # a store is generated only once every member it holds is placed
        complete.append(r["table"])
        if "keys" in r:
            tables = joined_tables(r)
            out.append(f"    // {r['struct']}: {r['file']} -> " + ", ".join(tables))
            out.append(f"    inline constexpr DBCSource {r['table']}[] =\n    {{\n" + "\n".join(lines) + "\n    };\n")
            joins = []
            for t in tables:
                key = r["keys"][t]
                kind = {"id": "Id", "parent": "Parent", "column": "Column"}[key[0]]
                field = key[1] if key[1] is not None else 0
                effect = f", {key[2]}" if len(key) > 2 else ""
                joins.append(f"        {{ &DB2Metadata::{t}, DBCJoinKey::{kind}, {field}{effect} }},")
            out.append(f"    inline constexpr DBCJoinTable {r['table']}Joins[] =\n    {{\n" + "\n".join(joins) + "\n    };\n")
            out.append(f"    inline constexpr DBCSourceInfo {r['table']}Info = {{ &DB2Metadata::{tables[0]}, "
                       f"{r['table']}, std::size({r['table']}), {r['table']}Joins, std::size({r['table']}Joins) }};\n")
            continue
        out.append(f"    // {r['struct']}: {r['file']} -> {r['table']}.db2")
        out.append(f"    inline constexpr DBCSource {r['table']}[] =\n    {{\n" + "\n".join(lines) + "\n    };\n")
        out.append(f"    inline constexpr DBCSourceInfo {r['table']}Info = {{ &DB2Metadata::{r['table']}, "
                   f"{r['table']}, std::size({r['table']}) }};\n")
    for r, x in pending:
        print(f"{r['table']:28} {x['member']:28} {x['kind']} distinct={x['distinct']:<6} "
              + ", ".join(f"{h[1]} ({h[0]:.0%})" for h in x["hits"][:8]))
    if pending:
        stores = len({r["table"] for r, _ in pending})
        print(f"{len(pending)} members of {stores} stores need a decision in {DECISIONS.name}", file=sys.stderr)
    if args.pending:
        return
    out.append("}\n\n#endif\n")
    OUTPUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}: {len(complete)} stores", file=sys.stderr)


if __name__ == "__main__":
    main()
